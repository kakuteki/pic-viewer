//***************************************************************
//	motor.c  DC モーターを H ブリッジ (IBT-2 / BTS7960) で動かす
//	PIC16F886  内部クロック 8MHz  XC8
//***************************************************************
#include <xc.h>
#pragma config CONFIG1 = 0x20C4

// 定数の宣言
#define _XTAL_FREQ	8000000		//8MHz for __delay_ms()

// IBT-2 モジュールとの接続
//	RC2 (CCP1) -> RPWM   正転の PWM
//	RC1 (CCP2) -> LPWM   逆転の PWM
//	RC0        -> R_EN と L_EN   1 で有効、0 で全オフ (惰性で停止)
#define MOTOR_EN	PORTCbits.RC0
#define DUTY_MAX	100			// CCPRxL の値 (x4 = 400 / 400) = 100%

//-----------------------------------------------------------
//	Main関数
//-----------------------------------------------------------
void main(void)
{
	// PICの初期化
	OSCCON = 0b01110000;	// 8MHzの内部クロックで動作
	ANSEL  = 0b00000000;	// アナログ入力 AN0からAN7 を無効
	ANSELH = 0b00000000;	// アナログ入力 AN8からAN13 を無効

	// 入出力の設定(0:出力 1:入力)
	TRISA = 0b11111111;		// PORTAの入力設定
	TRISB = 0b11111111;		// PORTBの入力設定
	TRISC = 0b11111000;		// RC0, RC1, RC2 を出力
	PORTC = 0b00000000;		// 出力の初期値 (EN = 0, PWM = 0)

	// PWM の設定  周波数 = 8MHz / (4 x 1 x 100) = 20kHz
	PR2     = 99;			// 周期 = (99 + 1) x 4 x 1 / 8MHz = 50us
	T2CON   = 0b00000100;	// Timer2 オン、プリスケール 1:1
	CCPR1L  = 0;			// 正転の時間幅 0
	CCPR2L  = 0;			// 逆転の時間幅 0
	CCP1CON = 0b00001100;	// CCP1 を PWM モードに (下位2ビット DC1B = 00)
	CCP2CON = 0b00001100;	// CCP2 を PWM モードに (下位2ビット DC2B = 00)

	// モーターの動作 (1秒ずつ)
	MOTOR_EN = 1;			// ドライバ有効 (両方の PWM が 0 なのでブレーキ)
	__delay_ms(1000);
	CCPR1L = 30;			// 正転 30% (30 x 4 = 120 / 400)
	__delay_ms(1000);
	CCPR1L = DUTY_MAX;		// 正転 100%
	__delay_ms(1000);
	CCPR1L = 0;				// ブレーキ (下側 2個がオン)
	__delay_ms(1000);
	CCPR2L = 50;			// 逆転 50% (50 x 4 = 200 / 400)
	__delay_ms(1000);
	CCPR2L = 0;				// ブレーキ
	__delay_ms(1000);
	MOTOR_EN = 0;			// ドライバ無効 (全オフ、惰性で停止)

	// メインループ
	while (1) {
		// ここにプログラムを記述
	}
}
